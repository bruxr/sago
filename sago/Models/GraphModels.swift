import Foundation

/// A typed neo4j property value.
enum PropertyValue: Hashable {
    case string(String)
    case int(Int)
    case double(Double)
    case bool(Bool)
    case date(Date)
    case list([PropertyValue])

    /// Human readable representation used in the inspector.
    var displayString: String {
        switch self {
        case .string(let value):
            return value
        case .int(let value):
            return value.formatted(.number.grouping(.never))
        case .double(let value):
            return value.formatted()
        case .bool(let value):
            return value ? "true" : "false"
        case .date(let value):
            return value.formatted(
                .dateTime
                    .year().month(.abbreviated).day()
                    .hour().minute(.twoDigits).second(.twoDigits)
                    .timeZone(.specificName(.short))
            )
        case .list(let values):
            return "[" + values.map(\.displayString).joined(separator: ", ") + "]"
        }
    }
}

/// A node returned by a cypher query.
struct GraphNode: Identifiable, Hashable {
    /// The internal id generated by neo4j (`<id>`).
    let id: Int
    var labels: [String]
    /// Only the caption fields (`name` / `title`) when loaded by `GraphStore.load`; the inspector fetches the rest on demand.
    /// Nodes returned by user queries carry all their properties.
    let properties: [String: PropertyValue]

    /// Text drawn inside / below the node on the canvas.
    var caption: String {
        for key in ["name", "title"] {
            if case .string(let value) = properties[key] {
                return value
            }
        }
        return labels.first ?? "\(id)"
    }
}

/// A relationship between two nodes.
struct GraphRelationship: Identifiable, Hashable {
    /// The internal id generated by neo4j (`<id>`).
    let id: Int
    let type: String
    let startNodeID: Int
    let endNodeID: Int
    var properties: [String: PropertyValue] = [:]
}

/// The element currently selected in the graph.
enum GraphSelection: Hashable {
    case node(Int)
    case relationship(Int)
}

/// Details about the current server connection.
struct ConnectionInfo: Hashable {
    let uri: String
    let database: String
    let user: String
}
